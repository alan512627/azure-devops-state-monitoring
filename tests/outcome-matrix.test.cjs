const fs = require('fs');
const assert = require('assert');
const source = fs.readFileSync('C4143-DVScale-Dashboard.user.js', 'utf8');
const D = {};
const grab = (start, end) => source.slice(source.indexOf(start), source.indexOf(end, source.indexOf(start)));
eval(grab('  D.normalizedTitle = ', '\n'));
eval(grab('  D.collect = ', '\n'));
eval(grab('  D.resultOutcomeKey = ', '  D.resultOutcomeSummary = '));
eval(grab('  D.crossRackIndex = ', '  D.crossRackOutcomeChips = '));
eval(grab('  D.OUTCOME_ABBR = ', '  D.outcomeMatrix = '));
const outcomes = { 'Fan test': ['Failed', 'Failed', 'Passed'], 'PSU test': ['Passed', 'Passed', 'Passed'], 'BMC test': ['Unspecified', 'Blocked', null] };
const racks = [0, 1, 2].map(r => ({ type: 'Feature', label: 'Rack #' + (r + 1), children: Object.keys(outcomes).filter(t => outcomes[t][r] !== null).map((t, i) => ({ id: (r + 1) * 100 + i, type: 'Test Case', title: t, latestTestPoint: { outcome: outcomes[t][r] } })) }));
const rows = D.outcomeMatrixRows(racks);
const fan = rows.find(r => r.title === 'Fan test'), bmc = rows.find(r => r.title === 'BMC test');
assert.deepStrictEqual(fan.cells.map(c => c.outcome), ['Failed', 'Failed', 'Passed']);
assert.deepStrictEqual([fan.counts.Failed, fan.counts.Passed, fan.present], [2, 1, 3]);
assert.deepStrictEqual([bmc.cells[0].outcome, bmc.cells[1].outcome, bmc.cells[2], bmc.present], ['Active', 'Blocked', null, 2]);
assert.deepStrictEqual(D.sortOutcomeMatrix(rows, 'failed').map(r => r.title), ['Fan test', 'BMC test', 'PSU test']);
assert.deepStrictEqual(D.sortOutcomeMatrix(rows, 'passed').map(r => r.title), ['PSU test', 'Fan test', 'BMC test']);
console.log('PASS: matrix rows hold each Rack\'s outcome per test item and sort by Failed / Passed');
